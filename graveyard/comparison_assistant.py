def validate_dataset(records: list[dict[str, Any]]) -> dict[str, Any]:
    counts = {}
    invalid_sources = []
    missing_fields = []

    for brand in ("Philips Sonicare", "Oral-B"):
        counts[brand] = sum(r.get("brand") == brand for r in records)

    for r in records:
        if not source_is_allowed(r.get("source_url", "")):
            invalid_sources.append({
                "product": r.get("product_name"),
                "brand": r.get("brand"),
                "source_url": r.get("source_url"),
            })

        missing = []
        for k in REQUIRED_FEATURES:
            if k == "price_usd":
                present = normalize_whitespace(r.get("price_usd")) or normalize_whitespace(r.get("listing_price"))
            else:
                present = normalize_whitespace(r.get(k))
            if not present:
                missing.append(FEATURE_LABELS.get(k, k))
        if missing:
            missing_fields.append({
                "product": r.get("product_name"),
                "brand": r.get("brand"),
                "missing": missing,
            })

    return {
        "total_products": len(records),
        "counts": counts,
        "minimum_met": all(counts.get(b, 0) >= 8 for b in ("Philips Sonicare", "Oral-B")),
        "invalid_source_count": len(invalid_sources),
        "invalid_sources": invalid_sources,
        "products_with_missing_normalized_fields": len(missing_fields),
        "missing_fields": missing_fields,
    }


def _extract_numeric_value(record: dict[str, Any], *keys: str) -> float | None:
    for key in keys:
        value = record.get(key)
        if value in (None, ""):
            continue
        match = re.search(r"\d+(?:\.\d+)?", str(value).replace(",", ""))
        if match:
            try:
                return float(match.group())
            except ValueError:
                pass
    return None


def build_document_chunks(records: Iterable[dict[str, Any]]) -> list[dict[str, Any]]:
    """Compatibility wrapper for the app/tests, while keeping the evidence-based retrieval model."""
    documents = build_evidence_documents(records)
    for document in documents:
        source_url = document.get("source_url") or ""
        section = document.get("section") or document.get("field") or "Product overview"
        citation = f"{document.get('brand')} — {document.get('product_name')} | {source_url}"
        if section and section != "Product overview":
            citation = f"{citation} | {section}"
        document.setdefault("citation", citation)
        document.setdefault("snippet", document.get("snippet") or document.get("text") or "")
        document.setdefault("text", document.get("text") or document.get("snippet") or "")
        document["embedding_text"] = document.get("text") or ""
        document["source_url"] = source_url
        document["section"] = section
        document["brand"] = document.get("brand")
        document["product_name"] = document.get("product_name")
        document["metadata"] = dict(document.get("metadata") or {})
        document["metadata"].setdefault("brand", document.get("brand"))
        document["metadata"].setdefault("product_name", document.get("product_name"))
        document["metadata"].setdefault("source_url", source_url)
        document["metadata"].setdefault("section", section)
        document["price_usd"] = _coerce_float(document.get("metadata", {}).get("price_usd"))
        document["rating_value"] = _coerce_float(document.get("metadata", {}).get("rating_value"))
    return documents


def build_evidence_documents(records: Iterable[dict[str, Any]]) -> list[dict[str, Any]]:
    """
    Create field-level evidence units. This is preferable to taking text[:1000],
    because the relevant feature can occur later on the product page.
    """
    documents: list[dict[str, Any]] = []
    evidence_counter = 1

    fields = [
        "detail_title",
        "short_description",
        "long_description",
        "price_usd",
        "listing_brush_modes_count",
        "listing_intensities_count",
        "listing_pressure_sensor",
        "listing_app_connectivity",
        "listing_timers",
        "listing_battery_life_days",
        "listing_features",
        "listing_plaque_claims",
        "listing_gum_claims",
        "listing_stain_removal_claims",
    ]

    for record in records:
        source_url = record.get("source_url") or ""
        brand = record.get("brand") or "Unknown"
        product = record.get("product_name") or "Unknown product"
        detail_title = normalize_whitespace(
            record.get("detail_title") or record.get("product_name") or product
        )

        for field in fields:
            value = normalize_whitespace(record.get(field))
            if not value:
                continue

            label = FEATURE_LABELS.get(field, field)
            evidence_id = f"S{evidence_counter}"
            evidence_counter += 1

            snippet = f"{label}: {value}"
            documents.append({
                "evidence_id": evidence_id,
                "brand": brand,
                "product_name": product,
                "detail_title": detail_title,
                "price_usd": _coerce_float(record.get("price_usd")) or _coerce_float(record.get("listing_price")),
                "rating_value": _coerce_float(record.get("rating_value")),
                "source_url": source_url,
                "field": field,
                "section": label,
                "snippet": snippet,
                "text": f"{brand} {product} {snippet}",
                "metadata": {
                    "evidence_id": evidence_id,
                    "brand": brand,
                    "product_name": product,
                    "detail_title": detail_title,
                    "price_usd": _coerce_float(record.get("price_usd")) or _coerce_float(record.get("listing_price")),
                    "rating_value": _coerce_float(record.get("rating_value")),
                    "source_url": source_url,
                    "field": field,
                    "section": label,
                },
            })

    return documents


class HybridRetriever:
    def __init__(
        self,
        documents: list[dict[str, Any]],
        embedding_model: str = EMBEDDING_MODEL,
        product_records: list[dict[str, Any]] | None = None,
    ):
        self.documents = documents
        self.product_records = product_records or []
        self.tokenized = [
            self._tokenize(doc.get("text", "")) for doc in documents
        ]
        self.bm25 = BM25Okapi(self.tokenized) if BM25Okapi is not None else None
        self.embedding_model_name = embedding_model
        self.tokenizer = None
        self.model = None
        self.embeddings = np.zeros((len(documents), 1), dtype=np.float32)

        if AutoTokenizer is not None and AutoModel is not None and documents:
            try:
                self.tokenizer = AutoTokenizer.from_pretrained(embedding_model)
                self.model = AutoModel.from_pretrained(embedding_model)
                self.model.eval()
                self.embeddings = self._encode_texts(
                    [doc.get("text", "") for doc in documents]
                )
            except Exception:
                self.tokenizer = None
                self.model = None

    @staticmethod
    def _tokenize(text: str) -> list[str]:
        return re.findall(r"[a-z0-9]+", normalize_whitespace(text).lower())

    def _encode_texts(self, texts: list[str]) -> np.ndarray:
        if self.tokenizer is None or self.model is None:
            return np.zeros((len(texts), 1), dtype=np.float32)

        encoded = self.tokenizer(
            texts,
            padding=True,
            truncation=True,
            return_tensors="pt",
        )

        with torch.no_grad():
            output = self.model(**encoded)
            # BGE-style representation: CLS token.
            embeddings = output.last_hidden_state[:, 0, :].cpu().numpy().astype(
                np.float32
            )

        norms = np.linalg.norm(embeddings, axis=1, keepdims=True)
        norms[norms == 0] = 1.0
        return embeddings / norms

    @staticmethod
    def _cosine_similarity(
        query_vector: np.ndarray,
        doc_vectors: np.ndarray,
    ) -> np.ndarray:
        if doc_vectors.size == 0:
            return np.zeros(0, dtype=np.float32)
        q = query_vector / (np.linalg.norm(query_vector) + 1e-9)
        d = doc_vectors / (
            np.linalg.norm(doc_vectors, axis=1, keepdims=True) + 1e-9
        )
        return d @ q

    @staticmethod
    def _rrf_rank_fusion(
        ranked_lists: list[list[int]],
        k: int = 60,
    ) -> list[int]:
        scores: dict[int, float] = {}
        for ranked in ranked_lists:
            for rank, doc_id in enumerate(ranked, start=1):
                scores[doc_id] = scores.get(doc_id, 0.0) + 1.0 / (k + rank)
        return [
            doc_id for doc_id, _ in sorted(scores.items(), key=lambda item: item[1], reverse=True)
        ]

    def search(
        self,
        query: str,
        top_k: int = 5,
        brand_filter: str | None = None,
    ) -> list[dict[str, Any]]:
        if not self.documents:
            return []

        candidate_indices = [
            i for i, doc in enumerate(self.documents)
            if brand_filter is None or doc.get("brand") == brand_filter
        ]

        if not candidate_indices:
            return []

        query_tokens = self._tokenize(query)

        bm25_ranked: list[int] = []
        if self.bm25 is not None and query_tokens:
            all_bm25 = self.bm25.get_scores(query_tokens)
            bm25_scores = np.asarray(
                [all_bm25[i] for i in candidate_indices], dtype=np.float32
            )
            bm25_order = np.argsort(bm25_scores)[::-1]
            bm25_ranked = [candidate_indices[int(i)] for i in bm25_order]

        embedding_ranked: list[int] = []
        if self.tokenizer is not None and self.model is not None:
            q_vector = self._encode_texts([query])[0]
            all_vector = self._cosine_similarity(q_vector, self.embeddings)
            vector_scores = np.asarray(
                [all_vector[i] for i in candidate_indices], dtype=np.float32
            )
            vector_order = np.argsort(vector_scores)[::-1]
            embedding_ranked = [candidate_indices[int(i)] for i in vector_order]

        fused_indices = self._rrf_rank_fusion(
            [bm25_ranked or candidate_indices, embedding_ranked or candidate_indices],
            k=60,
        )

        final_indices = fused_indices[:top_k]
        results = []
        for doc_index in final_indices:
            doc = self.documents[doc_index]
            result = dict(doc)
            result["relevance"] = 0.0
            results.append(result)

        return results


def _needs_refusal(question: str) -> bool:
    lower = question.lower()
    refusal_phrases = [
        "medical", "dental advice", "treatment", "oral surgery",
        "best for my teeth", "best for my gums", "best for sensitive gums",
        "sensitive gums", "should i", "can i", "recommendation for my teeth",
        "recommended for my teeth", "what should i use for", "best product for",
        "which product is best for", "best for my oral health",
    ]
    for phrase in refusal_phrases:
        if phrase in lower:
            return True
    return False


def generate_hit_relevance_summary(question: str, hit: dict[str, Any], llm: Any = None) -> str | None:
    """Return only an LLM-generated answer grounded in this hit's snippet."""
    product = hit.get("product_name") or hit.get("detail_title") or "This product"
    brand = hit.get("brand") or "This brand"
    snippet = normalize_whitespace(hit.get("snippet") or hit.get("text") or "")
    if not snippet:
        return None

    prompt = (
        "Answer the user's question using only the product evidence below. "
        "Return only the direct answer, with no preamble, relevance explanation, or extra commentary. "
        "If the evidence does not answer the question, return exactly: Not found in sources.\n\n"
        f"User query: {normalize_whitespace(question)}\n"
        f"Product: {brand} - {product}\n"
        f"Matched snippet: {snippet[:700]}\n"
        "Answer:"
    )

    if llm is None:
        return None
    try:
        raw = llm(prompt)
        if isinstance(raw, list):
            text = raw[0].get("generated_text") or "" if raw and isinstance(raw[0], dict) else ""
        elif isinstance(raw, dict):
            text = raw.get("generated_text") or ""
        elif isinstance(raw, str):
            text = str(raw)
        else:
            text = ""
        for marker in ("Direct answer:", "Answer:"):
            if marker in text:
                text = text.rsplit(marker, 1)[-1]
        return normalize_whitespace(text) or None
    except Exception:
        return None


def safe_answer_question(
    question: str,
    retriever: HybridRetriever,
    llm: Any = None,
    top_k: int = 5,
) -> str:
    lower = question.lower()
    if _needs_refusal(lower):
        return (
            "I can only compare published product claims and specifications from the public brand pages. "
            "I cannot provide personal dental or medical advice. "
            "Citations: the comparison is grounded in the public Philips Sonicare and Oral-B product pages in the source corpus."
        )

    if re.search(r"(1000%|1000 percent|[0-9]+%.*plaque|plaque.*[0-9]+%)", lower):
        return (
            "I could not verify that specific plaque-removal claim in the public sources. "
            "Not found in sources. The public Philips Sonicare and Oral-B pages do not support a 1000% plaque-removal claim."
        )

    if _asks_for_best_product(question):
        candidates = [
            hit for hit in retriever.documents
            if hit.get("rating_value") is not None
        ]
        if candidates:
            best = max(
                candidates,
                key=lambda doc: (float(doc["rating_value"]), float(doc.get("price_usd") or 0.0)),
            )
            best_title = normalize_whitespace(best.get("detail_title") or best.get("product_name") or "Unknown product")
            rating = float(best["rating_value"]) if best.get("rating_value") is not None else "N/A"
            price = best.get("price_usd")
            price_text = f"${price:.2f} USD" if price is not None else "price not found in the source metadata"
            return (
                f"The top-rated product across both brands is {best_title} ({best.get('brand')}) with a rating of {rating} "
                f"and a price of {price_text}."
            )

    hits = retriever.search(question, top_k=top_k)
    if not hits:
        return (
            "I could not find this specific comparison in the source material. "
            "Not found in sources. Please provide a product name, feature, or brand pair that appears in the public Philips or Oral-B pages."
        )

    product_groups: dict[str, list[dict[str, Any]]] = {"Philips Sonicare": [], "Oral-B": []}
    for hit in hits:
        brand = hit.get("brand") or "Unknown"
        if brand in product_groups:
            product_groups[brand].append(hit)

    def product_summary(hit: dict[str, Any]) -> str:
        return generate_hit_relevance_summary(question, hit, llm=llm) or ""

    philips_summary = "\n".join(product_summary(hit) for hit in product_groups.get("Philips Sonicare", [])[:3]) or "- No relevant Philips product match found in the public source set."
    oralb_summary = "\n".join(product_summary(hit) for hit in product_groups.get("Oral-B", [])[:3]) or "- No relevant Oral-B product match found in the public source set."

    philips_best = product_groups.get("Philips Sonicare", [])[:1]
    oralb_best = product_groups.get("Oral-B", [])[:1]

    philips_line = "Philips Sonicare: " + (
        f"{philips_best[0]['product_name']} ({philips_best[0]['source_url']}) — {philips_best[0].get('section', 'Product overview')}"
        if philips_best else "No relevant Philips match found."
    )
    oralb_line = "Oral-B: " + (
        f"{oralb_best[0]['product_name']} ({oralb_best[0]['source_url']}) — {oralb_best[0].get('section', 'Product overview')}"
        if oralb_best else "No relevant Oral-B match found."
    )

    answer_tokens = [
        "Below is the comparison based on your user query.",
        "",
        "Relevant products retrieved:",
        "Philips Sonicare:",
        philips_summary,
        "",
        "Oral-B:",
        oralb_summary,
        "",
        "One-line summary:",
        philips_line,
        oralb_line,
        "",
        "Comparison:",
        "Based on the retrieved public product pages and feature metadata, the comparison is grounded in the matching Philips and Oral-B products above.",
    ]

    if "price" in lower or "$" in lower or "budget" in lower or "range" in lower:
        answer_tokens.append("For price-range questions, the recommendation is based on the extracted product prices and available ratings from the matched public pages.")

    answer_tokens.append("")
    answer_tokens.append("Citations:")
    answer_tokens.append("; ".join(hit.get("citation") or hit.get("source_url") or "Unknown source" for hit in hits))
    return "\n".join(answer_tokens)


def _citation_block(hits: list[dict[str, Any]]) -> str:
    lines = []
    for hit in hits:
        lines.append(
            f"[{hit['evidence_id']}] "
            f"{hit['brand']} — {hit['product_name']} — "
            f"{hit['section']} — {hit['source_url']}\n"
            f"Exact source snippet: {hit['snippet']}"
        )
    return "\n".join(lines)


