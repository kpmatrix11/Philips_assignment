def _extract_budget_range(question: str) -> tuple[float | None, float | None] | None:
    lower = question.lower()
    if not any(word in lower for word in ("price", "budget", "range", "under", "below", "between", "$")):
        return None

    matches = [
        re.search(r"(\d+(?:\.\d+)?)\s*(?:-|–|to|through)\s*(\d+(?:\.\d+)?)", lower),
        re.search(r"under\s*(\d+(?:\.\d+)?)", lower),
        re.search(r"below\s*(\d+(?:\.\d+)?)", lower),
        re.search(r"\$\s*(\d+(?:\.\d+)?)\s*(?:-|–|to|through)\s*\$?\s*(\d+(?:\.\d+)?)", lower),
    ]
    for match in matches:
        if match:
            if len(match.groups()) == 2 and match.group(1) and match.group(2):
                lo, hi = float(match.group(1)), float(match.group(2))
                return (min(lo, hi), max(lo, hi))
            if len(match.groups()) == 1 and match.group(1):
                return (0.0, float(match.group(1)))
    return None


