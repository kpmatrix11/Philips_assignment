def run_evaluation(
    retriever: HybridRetriever,
    llm: Any = None,
) -> dict[str, Any]:
    results = []
    retrieval_hits = 0
    citation_pass = 0
    refusal_pass = 0
    unsupported_pass = 0

    for case in EVALUATION_QUESTIONS:
        result = answer_question(case["question"], retriever, llm=llm)
        hit_brands = {h.get("brand") for h in result["hits"]}

        if case["must_retrieve"]:
            retrieval_ok = all(
                brand in hit_brands for brand in case["must_retrieve"]
            )
        else:
            retrieval_ok = len(result["hits"]) > 0 or case["must_refuse"]

        if retrieval_ok:
            retrieval_hits += 1

        citation_ok = (
            result["refused"]
            or (
                len(result["citations"]) > 0
                and all(
                    cid in {h["evidence_id"] for h in result["hits"]}
                    for cid in result["citations"]
                )
            )
        )
        if citation_ok:
            citation_pass += 1

        refusal_ok = result["refused"] == case["must_refuse"]
        if refusal_ok:
            refusal_pass += 1

        unsupported_ok = len(result["unsupported_claims"]) == 0
        if unsupported_ok:
            unsupported_pass += 1

        results.append({
            "question": case["question"],
            "retrieval_ok": retrieval_ok,
            "citation_ok": citation_ok,
            "refusal_ok": refusal_ok,
            "unsupported_claims_ok": unsupported_ok,
            "answer": result["answer"],
            "citations": result["citations"],
            "unsupported_claims": result["unsupported_claims"],
        })

    total = len(EVALUATION_QUESTIONS)

    return {
        "total_questions": total,
        "retrieval_hit_rate": round(retrieval_hits / total, 3),
        "citation_pass_rate": round(citation_pass / total, 3),
        "refusal_pass_rate": round(refusal_pass / total, 3),
        "unsupported_claim_check_pass_rate": round(
            unsupported_pass / total, 3
        ),
        "results": results,
    }


