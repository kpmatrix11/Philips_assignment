def _valid_citation_ids(answer: str, allowed_ids: set[str]) -> set[str]:
    found = set(re.findall(r"\[(S\d+)\]", answer))
    return found.intersection(allowed_ids)


def _sentence_tokens(text: str) -> set[str]:
    stop = {
        "the", "a", "an", "and", "or", "to", "of", "for", "with",
        "is", "are", "has", "have", "in", "on", "from", "this",
        "that", "than", "between", "does", "do", "it",
    }
    return {
        token for token in re.findall(r"[a-z0-9]+", text.lower())
        if token not in stop and len(token) > 2
    }


def detect_unsupported_claims(answer: str, hits: list[dict[str, Any]]) -> list[str]:
    """
    Basic automated guard, not a formal factuality proof.
    A factual sentence should have a valid [S#] citation and should share
    meaningful terms with at least one cited snippet.
    """
    by_id = {h["evidence_id"]: h for h in hits}
    issues = []

    for sentence in re.split(r"(?<=[.!?])\s+", answer):
        sentence = sentence.strip()
        if not sentence or sentence.startswith("Citations:"):
            continue

        ids = re.findall(r"\[(S\d+)\]", sentence)
        if not ids:
            continue

        cited_text = " ".join(
            by_id[cid]["snippet"] for cid in ids if cid in by_id
        )
        if not cited_text:
            issues.append(f"No valid evidence for sentence: {sentence}")
            continue

        overlap = _sentence_tokens(sentence) & _sentence_tokens(cited_text)
        if len(overlap) < 2:
            issues.append(f"Low evidence overlap: {sentence}")

    return issues


def _is_comparison_query(question: str) -> bool:
    lower = question.lower()
    explicit_comparison = re.search(
        r"\b(compare|comparison|versus|vs\.?|difference|differences|between|better)\b",
        lower,
    )
    if explicit_comparison:
        return True
    if "which brand" in lower:
        return True
    mentions_philips = "philips" in lower or "sonicare" in lower
    mentions_oralb = "oral-b" in lower or "oral b" in lower or "oralb" in lower
    return mentions_philips and mentions_oralb


def _comparison_features_for_question(question: str) -> list[str]:
    lower = question.lower()
    keywords = {
        "price_usd": r"\b(price|cost|budget|\$)\b",
        "rating_value": r"\b(rating|rated|reviews?)\b",
        "listing_brush_modes_count": r"\b(brush|brushing|cleaning)\s+modes?\b|\bmodes?\b",
        "listing_intensities_count": r"\bintensit(?:y|ies)\b",
        "listing_pressure_sensor": r"\bpressure\b",
        "listing_app_connectivity": r"\b(app|bluetooth|connectivity|connected)\b",
        "listing_timers": r"\b(timer|timing)\b",
        "listing_battery_life_days": r"\b(battery|charging|charge)\b",
        "listing_features": r"\b(features?|included|accessories)\b",
        "listing_plaque_claims": r"\bplaque\b",
        "listing_gum_claims": r"\b(gum|gums|gumline|gingiv\w*)\b",
        "listing_stain_removal_claims": r"\b(stain|whiten|whitening)\b",
    }
    selected = [field for field, pattern in keywords.items() if re.search(pattern, lower)]
    return selected or list(COMPARISON_FEATURES)


def _comparison_value(record: dict[str, Any], field: str) -> Any:
    value = record.get(field)
    if value not in (None, ""):
        return value
    for alias in PRODUCT_FIELD_ALIASES.get(field, ()):
        value = record.get(alias)
        if value not in (None, ""):
            return value
    return None


def _generate_comparison_conclusion(
    question: str,
    table: list[dict[str, Any]],
    llm: Any = None,
) -> tuple[str | None, bool]:
    if not table:
        return None, False

    table_text = json.dumps(table, ensure_ascii=False, indent=2)
    if llm is not None:
        prompt = f"""
You are a product comparison analyst. Answer the user's exact question using only the comparison table provided.

Instructions:
- Lead with the direct answer to the question; do not describe the table or give a generic summary.
- Address every part of the question and discuss only the requested feature(s).
- Apply the same method to any feature named in the user query. For comparisons asking which brand or product claims/has more, inspect all relevant rows, identify each brand's highest supported value or claim, then compare only when the units and reference points are compatible.
- For each conclusion, name the relevant product(s), report the exact supporting value or claim, and cite its source. Explain when the table does not support a direct comparison.
- Example of the method, not an assumption about the current query: if asked "Does Oral-B or Philips claim more plaque removal?", report each brand's highest plaque-removal claim and compare them only if the claims are directly comparable.
- Use the values and product names in the table. Do not infer values or make claims that the table does not support.
- Treat "Not found in sources" as missing information, never as evidence that a product lacks a feature.
- If the question asks which product or brand has more, state the comparison only when the table supports it; otherwise explain what cannot be determined.
- Cite product-specific facts with a markdown link using that row's exact Source URL.
- Keep the answer concise and in plain English. Do not give personal dental or medical advice.

User query:
{question}

Comparison table (all matching products; values are source metadata):
{table_text}

Direct answer:
""".strip()
        try:
            raw = llm(prompt)
            if isinstance(raw, list) and raw and isinstance(raw[0], dict):
                text = raw[0].get("generated_text") or ""
            elif isinstance(raw, dict):
                text = raw.get("generated_text") or ""
            else:
                text = str(raw)
            conclusion = text.rsplit("Direct answer:", 1)[-1].strip()
            conclusion = normalize_whitespace(conclusion)
            if conclusion:
                return conclusion, True
        except Exception:
            pass

    return None, False


def answer_question(
    question: str,
    retriever: HybridRetriever,
    llm: Any = None,
    top_k: int = 8,
) -> dict[str, Any]:
    if _needs_refusal(question):
        return {
            "answer": (
                "I can compare published Philips Sonicare and Oral-B product "
                "claims/specifications, but I cannot provide personal dental "
                "or medical advice."
            ),
            "citations": [],
            "hits": [],
            "refused": True,
            "unsupported_claims": [],
        }

    if _is_comparison_query(question) and not _asks_for_best_product(question):
        table = build_feature_comparison(
            getattr(retriever, "product_records", []),
            question,
        )
        conclusion, llm_used = _generate_comparison_conclusion(question, table, llm)
        source_urls = sorted({
            row["Source"]
            for row in table
            if row.get("Source") and row["Source"] != "Not found in sources"
        })
        return {
            "answer": conclusion,
            "conclusion": conclusion,
            "comparison_table": table,
            "llm_used": llm_used,
            "citations": source_urls,
            "hits": [],
            "refused": False,
            "unsupported_claims": [],
        }

    budget_range = _extract_budget_range(question)
    if budget_range:
        min_price, max_price = budget_range
        brand_filter = _extract_brand_filter(question)
        matched = [
            doc for doc in retriever.documents
            if doc.get("price_usd") is not None
            and min_price <= float(doc["price_usd"]) <= max_price
            and (brand_filter is None or doc.get("brand") == brand_filter)
        ]
        if matched:
            unique_titles: list[str] = []
            seen_titles: set[str] = set()
            for doc in sorted(matched, key=lambda doc: (float(doc.get("rating_value") or 0.0), float(doc.get("price_usd") or 0.0)), reverse=True):
                title = normalize_whitespace(doc.get("detail_title") or doc.get("product_name") or "Unknown product")
                if title and title not in seen_titles:
                    unique_titles.append(title)
                    seen_titles.add(title)
            answer = (
                f"Products in the ${min_price:.0f}-${max_price:.0f} range: "
                + "; ".join(unique_titles[:10])
            )
            return {
                "answer": normalize_whitespace(answer),
                "citations": [],
                "hits": matched[:10],
                "refused": False,
                "unsupported_claims": [],
            }

    if _asks_for_best_product(question):
        brand_filter = _extract_brand_filter(question)
        candidates = [
            doc for doc in retriever.documents
            if doc.get("rating_value") is not None
            and (brand_filter is None or doc.get("brand") == brand_filter)
        ]
        if candidates:
            best = max(
                candidates,
                key=lambda doc: (float(doc["rating_value"]), float(doc.get("price_usd") or 0.0)),
            )
            title = normalize_whitespace(best.get("detail_title") or best.get("product_name") or "Unknown product")
            rating = float(best["rating_value"]) if best.get("rating_value") is not None else "N/A"
            price = best.get("price_usd")
            price_text = f"${price:.2f} USD" if price is not None else "price not found in the source metadata"
            answer = (
                f"The highest-rated product is {title} ({best.get('brand')}) with a rating of {rating} "
                f"and a price of {price_text}."
            )
            if llm is not None:
                prompt = f"""
You are a grounded competitive-intelligence assistant.

Rules:
- Use ONLY the retrieved evidence and product metadata supplied below.
- When the user asks for the "best" or "highest-rated" product, prioritize the product metadata with the highest rating_value in the retrieved results.
- Use detail_title for the product name and price_usd for price.
- If the user asks for a price range, return only the matched product titles in that range.
- Use the evidence text only to support the answer; do not invent missing facts.
- Every factual product statement must use source evidence IDs like [S12] when cited.
- Do not give personal dental or medical advice.
- Keep Philips Sonicare and Oral-B claims clearly attributed.

Question:
{question}

Retrieved metadata and snippets:
{_citation_block(candidates[:10])}

Answer:
""".strip()
                try:
                    raw = llm(prompt)[0]["generated_text"]
                    answer = raw.split("Answer:", 1)[-1].strip() or answer
                except Exception:
                    pass
            return {
                "answer": answer,
                "citations": [best.get("evidence_id", "")],
                "hits": candidates[:10],
                "refused": False,
                "unsupported_claims": [],
            }

    hits = retriever.search(question, top_k=top_k)

    if not hits:
        return {
            "answer": "Not found in sources.",
            "citations": [],
            "hits": [],
            "refused": False,
            "unsupported_claims": [],
        }

    context = _citation_block(hits)
    allowed_ids = {h["evidence_id"] for h in hits}

    if llm is not None:
        prompt = f"""
You are a grounded competitive-intelligence assistant.

Rules:
- Use ONLY the evidence supplied below.
- Do not use general knowledge.
- Do not infer missing specifications.
- If the evidence does not support the requested fact, say exactly:
  "Not found in sources."
- When the user asks for the "best" or "highest-rated" product, prioritize the retrieved product metadata with the highest rating_value; the name should come from detail_title and the numeric rating should come from rating_value.
- When the user asks for a price range, return only the matched product titles in that range.
- Every factual product statement must end with one or more evidence IDs such as [S12].
- Never invent an evidence ID.
- Do not give personal medical or dental advice.
- Do not declare a product "best", "winner", "superior", or "recommended" without citing the rating metadata in the retrieved evidence.
- Keep Philips Sonicare and Oral-B claims clearly attributed.

Question:
{question}

Evidence:
{context}

Answer:
""".strip()

        try:
            raw = llm(prompt)[0]["generated_text"]
            answer = raw.split("Answer:", 1)[-1].strip()
        except Exception:
            answer = ""

        valid_ids = _valid_citation_ids(answer, allowed_ids)
        if not answer or not valid_ids:
            answer = deterministic_answer(question, hits)

    else:
        answer = deterministic_answer(question, hits)

    answer = normalize_whitespace(answer)
    unsupported = detect_unsupported_claims(answer, hits)
    citations = sorted(_valid_citation_ids(answer, allowed_ids))

    return {
        "answer": answer,
        "citations": citations,
        "hits": hits,
        "refused": False,
        "unsupported_claims": unsupported,
    }


def deterministic_answer(
    question: str,
    hits: list[dict[str, Any]],
) -> str:
    """
    Safe fallback: report retrieved evidence rather than inventing a conclusion.
    """
    lines = [
        "Based on the retrieved US public-source evidence:",
    ]

    for hit in hits[:6]:
        lines.append(
            f"- {hit['brand']} — {hit['product_name']}: "
            f"{hit['snippet']} [{hit['evidence_id']}]"
        )

    lines.append(
        "Please note: "
        "A fact not represented in these sources is treated as "
        "\"Not found in sources.\""
    )
    return "\n".join(lines)


def build_feature_comparison(
    records: list[dict[str, Any]],
    question: str | None = None,
) -> list[dict[str, Any]]:
    """Return one metadata row per Philips/Oral-B product for a comparison."""
    features = _comparison_features_for_question(question or "")
    rows = []

    for record in records:
        brand = normalize_brand(record.get("brand"))
        if brand not in {"Philips Sonicare", "Oral-B"}:
            continue

        row = {
            "Brand": brand,
            "Product": normalize_product_name(record),
            "Source": normalize_whitespace(
                record.get("source_url") or record.get("product_url") or record.get("listing_url")
            ) or "Not found in sources",
        }
        for feature in features:
            value = _comparison_value(record, feature)
            if feature in {"price_usd", "rating_value"}:
                value = _coerce_float(value)
            elif feature in {"listing_brush_modes_count", "listing_intensities_count"}:
                numeric_value = _coerce_float(value)
                value = int(numeric_value) if numeric_value is not None and numeric_value.is_integer() else numeric_value
            else:
                value = normalize_whitespace(value)
            row[FEATURE_LABELS.get(feature, feature)] = value if value not in (None, "") else "Not found in sources"
        rows.append(row)

    return rows


