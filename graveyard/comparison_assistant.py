def normalize_whitespace(value: Any) -> str:
    if value is None:
        return ""
    text = str(value).replace("\u200b", "").replace("\ufeff", "")
    text = unicodedata.normalize("NFKD", text)
    text = text.encode("ascii", "ignore").decode("ascii")
    text = re.sub(r"[\x00-\x1f\x7f]+", " ", text)
    return re.sub(r"\s+", " ", text).strip()


def _coerce_float(value: Any) -> float | None:
    if value in (None, ""):
        return None
    text = str(value).strip().replace(",", "")
    match = re.search(r"-?\d+(?:\.\d+)?", text)
    if not match:
        return None
    try:
        return float(match.group(0))
    except ValueError:
        return None


def normalize_product_name(record: dict[str, Any]) -> str:
    for key in ("detail_title", "product_name", "model_codes"):
        candidate = record.get(key)
        if candidate:
            return normalize_whitespace(candidate)
    return "Unknown product"


def normalize_brand(value: Any) -> str:
    value = normalize_whitespace(value).lower()
    if "oral-b" in value or "oral b" in value:
        return "Oral-B"
    if "philips" in value or "sonicare" in value:
        return "Philips Sonicare"
    return normalize_whitespace(value) or "Unknown"


